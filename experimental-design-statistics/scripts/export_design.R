# export_design.R
# Bundle a complete design package for lab + downstream analysis.
#
# Inputs:
#   - batch_design: data frame with sample_id, batch, condition, etc.
#   - design_params: list of assay, conditions, n_per_group, power, alpha,
#     effect_size, multiple_testing, batches (optional), ...
# Outputs (written to output_dir):
#   - batch_layout_for_lab.csv, statistical_analysis_plan.md,
#     lab_protocol_checklist.md, batch_design.rds, design_parameters.rds,
#     design_parameters.json.

.has <- function(pkg) requireNamespace(pkg, quietly = TRUE)

#' Export the batch assignment as a lab-ready CSV
#'
#' @param batch_design Data frame with sample-to-batch assignments
#' @param output_file Output CSV path
export_batch_layout <- function(batch_design,
                                output_file = "batch_layout_for_lab.csv") {
  priority <- c("sample_id","batch","condition","processing_order",
                "plate","well","overall_sequence")
  present_priority <- intersect(priority, colnames(batch_design))
  other <- setdiff(colnames(batch_design), present_priority)
  ordered <- batch_design[, c(present_priority, other), drop = FALSE]

  if ("batch" %in% colnames(ordered)) {
    if ("processing_order" %in% colnames(ordered))
      ordered <- ordered[order(ordered$batch, ordered$processing_order), ]
    else
      ordered <- ordered[order(ordered$batch), ]
  }

  utils::write.csv(ordered, output_file, row.names = FALSE)
  cat(sprintf("✓ Batch layout exported: %d rows / %s\n",
              nrow(ordered), output_file))
  invisible(ordered)
}

#' Export the statistical analysis plan as Markdown
#'
#' @param design_params Named list of design parameters
#' @param output_file Markdown output path
export_statistical_plan <- function(design_params,
                                    output_file = "statistical_analysis_plan.md") {
  lines <- c(
    "# Statistical Analysis Plan",
    "",
    sprintf("Generated: %s", format(Sys.time(), "%Y-%m-%d %H:%M:%S")),
    "",
    "---",
    "",
    "## Experimental design",
    sprintf("- Assay: %s", design_params$assay),
    sprintf("- Conditions: %s", paste(design_params$conditions, collapse = ", ")),
    sprintf("- Sample size: %d per group (%d total)",
            design_params$n_per_group,
            design_params$n_per_group * length(design_params$conditions))
  )

  if (!is.null(design_params$batches)) {
    lines <- c(lines, "",
               sprintf("- Batch structure: %d processing batches", design_params$batches),
               "- Each batch contains all experimental conditions (no confounding).")
  }

  lines <- c(lines, "", "## Power analysis")
  if (!is.null(design_params$power))
    lines <- c(lines,
               sprintf("- Target power: %.2f", design_params$power),
               sprintf("- Minimum detectable effect: %s-fold", design_params$effect_size),
               sprintf("- Significance threshold: alpha = %s", design_params$alpha))

  lines <- c(lines, "", "## Statistical methods",
             "- DE analysis: DESeq2 (negative binomial GLM).",
             sprintf("- Multiple-testing correction: %s", design_params$multiple_testing),
             "- FDR threshold: q < 0.05.")

  if (!is.null(design_params$batches) && design_params$batches > 1)
    lines <- c(lines, "",
               "## Batch handling",
               "- Design formula: `~ batch + condition`.",
               "- Fallbacks if residual batch effects: SVA, ComBat, RUVSeq.")

  lines <- c(lines, "",
             "## Quality control",
             "- Library size > 10M reads per sample.",
             "- Alignment rate > 80%.",
             "- rRNA contamination < 10%.",
             "- Within-group sample correlation > 0.8.",
             "- Filter genes below assay-specific count threshold before DE.",
             "",
             "## Workflow",
             "1. FastQC + alignment QC.",
             "2. DESeq2 size-factor normalization (or TMM via edgeR).",
             "3. PCA + batch-confounding check.",
             "4. DESeq2 DE with pre-specified multiple-testing method.",
             "5. Volcano / MA visualization.",
             "6. Downstream enrichment / pathway analysis.",
             "",
             "## Reproducibility",
             "- Random seed pinned for all stochastic steps.",
             "- R / Bioconductor versions recorded.",
             "- Code in version control.",
             "- Raw data deposited at GEO / SRA (or institutional equivalent).",
             "",
             "---",
             "",
             "*Generated by the experimental-design-statistics workflow.*"
  )

  writeLines(lines, output_file)
  cat(sprintf("✓ Analysis plan exported: %s\n", output_file))
  invisible(lines)
}

#' Generate a lab protocol checklist as Markdown
generate_lab_protocol <- function(batch_design = NULL,
                                  metadata_fields = c("date","operator","reagent_lots","instrument"),
                                  output_file = "lab_protocol_checklist.md") {
  lines <- c(
    "# Lab Protocol Checklist",
    "",
    sprintf("Generated: %s", format(Sys.time(), "%Y-%m-%d %H:%M:%S")),
    "",
    "---"
  )

  if (!is.null(batch_design)) {
    n_batch <- length(unique(batch_design$batch))
    lines <- c(lines, "",
               sprintf("- Total samples: %d", nrow(batch_design)),
               sprintf("- Number of batches: %d", n_batch),
               "- Batch assignment file: batch_layout_for_lab.csv")
  }

  lines <- c(lines, "",
             "## Before starting",
             "- [ ] Review batch assignment file.",
             "- [ ] Verify all samples are available.",
             "- [ ] Prepare reagents; check expiration dates.",
             "- [ ] Record reagent lot numbers.",
             "- [ ] Calibrate instruments as needed.",
             "- [ ] Randomize sample positions within plates.",
             "",
             "## Per batch — documentation (critical)",
             "Record the following before processing each batch:"
  )

  meta_lines <- list(
    date          = "- [ ] Processing date (YYYY-MM-DD)",
    operator      = "- [ ] Operator / technician name",
    reagent_lots  = "- [ ] Reagent lot numbers (all kits)",
    instrument    = "- [ ] Instrument / equipment ID",
    plate         = "- [ ] Plate barcode and well positions",
    library_prep  = "- [ ] Library prep kit name and lot",
    protocol_deviations = "- [ ] Protocol deviations (if any)"
  )
  for (f in metadata_fields)
    if (!is.null(meta_lines[[f]])) lines <- c(lines, meta_lines[[f]])

  lines <- c(lines, "",
             "## Per batch — sample processing",
             "- [ ] Samples processed per batch assignment.",
             "- [ ] Randomized within batch (avoid systematic patterns).",
             "- [ ] Avoid plate edge wells when possible.",
             "- [ ] Include positive and negative controls.",
             "- [ ] Record sample failures.",
             "",
             "## Quality checks during processing",
             "- [ ] RNA integrity (RIN if RNA-based assay).",
             "- [ ] Concentration measurements.",
             "- [ ] Visual inspection for contamination.",
             "- [ ] Volume checks.",
             "",
             "## Post-processing",
             "- [ ] Library QC (Bioanalyzer / TapeStation).",
             "- [ ] Qubit quantification.",
             "- [ ] Pooling calculations.",
             "- [ ] Submit for sequencing.",
             "",
             "## Critical rules",
             "1. **Never** process all samples from one condition in a single batch.",
             "2. Document everything.",
             "3. Randomize within batch.",
             "4. Include shared control samples across batches if multi-week processing.",
             "",
             "---",
             "",
             "*Generated by the experimental-design-statistics workflow.*")

  writeLines(lines, output_file)
  cat(sprintf("✓ Lab protocol exported: %s\n", output_file))
  invisible(lines)
}

#' Export the complete design package (CSV + MD + RDS + JSON)
#'
#' @param batch_design Data frame with sample-to-batch assignment
#' @param design_params Named list of design parameters
#' @param output_dir Directory to write all artifacts (created if missing)
export_complete_design <- function(batch_design, design_params,
                                   output_dir = "design_results") {
  if (!dir.exists(output_dir)) dir.create(output_dir, recursive = TRUE)

  cat("\n=== Exporting complete design ===\n")

  batch_file <- file.path(output_dir, "batch_layout_for_lab.csv")
  export_batch_layout(batch_design, batch_file)

  plan_file <- file.path(output_dir, "statistical_analysis_plan.md")
  export_statistical_plan(design_params, plan_file)

  protocol_file <- file.path(output_dir, "lab_protocol_checklist.md")
  generate_lab_protocol(batch_design, output_file = protocol_file)

  batch_rds <- file.path(output_dir, "batch_design.rds")
  saveRDS(batch_design, batch_rds)
  cat(sprintf("   saved: %s\n", batch_rds))

  params_rds <- file.path(output_dir, "design_parameters.rds")
  saveRDS(design_params, params_rds)
  cat(sprintf("   saved: %s\n", params_rds))

  params_json <- file.path(output_dir, "design_parameters.json")
  if (.has("jsonlite")) {
    jsonlite::write_json(design_params, params_json, pretty = TRUE, auto_unbox = TRUE)
  } else {
    writeLines(utils::capture.output(utils::str(design_params)), params_json)
  }
  cat(sprintf("   saved: %s\n", params_json))

  cat("\n=== Export Complete ===\n")
  cat("Files:\n")
  for (f in c(batch_file, plan_file, protocol_file, batch_rds, params_rds, params_json))
    cat(" - ", f, "\n")

  invisible(list(
    batch_layout = batch_file,
    analysis_plan = plan_file,
    lab_protocol = protocol_file,
    batch_design_rds = batch_rds,
    design_params_rds = params_rds,
    design_params_json = params_json
  ))
}
